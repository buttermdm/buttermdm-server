package com.buttermdm.plugins.melonmaintenance.persistence.domain;

import java.io.Serializable;

/**
 * <p>Immutable audit record for technician break-glass force-install actions (`RESUME §7.6 B-10`).</p>
 *
 * @author buttermdm
 */
public class MelonMaintenanceForceAudit implements Serializable {

    private static final long serialVersionUID = 1L;

    private Integer id;
    private int deviceId;
    private int customerId;
    private int userId;
    private String username;
    private String ticketRef;
    private String packageName;
    private String reason;
    private long createdAt;

    public MelonMaintenanceForceAudit() {
    }

    public Integer getId() {
        return id;
    }

    public void setId(Integer id) {
        this.id = id;
    }

    public int getDeviceId() {
        return deviceId;
    }

    public void setDeviceId(int deviceId) {
        this.deviceId = deviceId;
    }

    public int getCustomerId() {
        return customerId;
    }

    public void setCustomerId(int customerId) {
        this.customerId = customerId;
    }

    public int getUserId() {
        return userId;
    }

    public void setUserId(int userId) {
        this.userId = userId;
    }

    public String getUsername() {
        return username;
    }

    public void setUsername(String username) {
        this.username = username;
    }

    public String getTicketRef() {
        return ticketRef;
    }

    public void setTicketRef(String ticketRef) {
        this.ticketRef = ticketRef;
    }

    public String getPackageName() {
        return packageName;
    }

    public void setPackageName(String packageName) {
        this.packageName = packageName;
    }

    public String getReason() {
        return reason;
    }

    public void setReason(String reason) {
        this.reason = reason;
    }

    public long getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(long createdAt) {
        this.createdAt = createdAt;
    }
}
